import { describe, expect, it } from "vitest";
import {
  AI_VIDEO_FALLBACK_MS,
  aiGenerateFile,
  aiGenerateFileName,
  aiVideoInsertDurationMs,
  findImportedAsset,
  formatAtMs,
  validateAiGeneratePrompt,
} from "../aiGenerate";
import type { MediaAssetRecord } from "../mediaStore";

const record = (name: string, durationMs?: number): MediaAssetRecord =>
  ({ id: `id-${name}`, projectId: "p1", kind: "image", name, mime: "image/png", size: 10, durationMs, blob: new Blob(["x"]), createdAt: 1 }) as MediaAssetRecord;

describe("validateAiGeneratePrompt", () => {
  it("requires a non-empty prompt", () => {
    expect(validateAiGeneratePrompt("")).toBe("Describe what you want first.");
    expect(validateAiGeneratePrompt("   ")).toBe("Describe what you want first.");
    expect(validateAiGeneratePrompt("a sunset")).toBeNull();
  });
  it("caps very long prompts", () => {
    expect(validateAiGeneratePrompt("x".repeat(1001))).toBe("Keep the prompt under 1000 characters.");
    expect(validateAiGeneratePrompt("x".repeat(1000))).toBeNull();
  });
});

describe("aiGenerateFile", () => {
  it("names image and video results distinctly and uniquely", () => {
    expect(aiGenerateFileName("image", 1000)).toBe("AI image 1000.png");
    expect(aiGenerateFileName("video", 1000)).toBe("AI video 1000.mp4");
    expect(aiGenerateFileName("image", 1001)).not.toBe(aiGenerateFileName("image", 1000));
  });
  it("builds an importable File from the generated bytes, keeping the blob type", () => {
    const file = aiGenerateFile("image", new Blob(["bytes"], { type: "image/jpeg" }), 42);
    expect(file?.name).toBe("AI image 42.png");
    expect(file?.type).toBe("image/jpeg");
    expect(file?.size).toBe(5);
  });
  it("falls back to png/mp4 when the blob carries no type, and refuses empty bytes", () => {
    expect(aiGenerateFile("image", new Blob(["x"]), 1)?.type).toBe("image/png");
    expect(aiGenerateFile("video", new Blob(["x"]), 1)?.type).toBe("video/mp4");
    expect(aiGenerateFile("image", new Blob([]), 1)).toBeNull();
  });
});

describe("media-bin handoff", () => {
  it("finds the just-imported record by its unique name", () => {
    const records = [record("AI image 1.png"), record("AI image 2.png")];
    expect(findImportedAsset(records, "AI image 2.png")?.id).toBe("id-AI image 2.png");
    expect(findImportedAsset(records, "AI image 9.png")).toBeNull();
  });
  it("uses the probed video length for the insert, falling back to the requested clip length", () => {
    expect(aiVideoInsertDurationMs({ durationMs: 4800 })).toBe(4800);
    expect(aiVideoInsertDurationMs({ durationMs: null })).toBe(AI_VIDEO_FALLBACK_MS);
    expect(aiVideoInsertDurationMs({ durationMs: 0 })).toBe(AI_VIDEO_FALLBACK_MS);
  });
});

describe("formatAtMs", () => {
  it("formats playhead times as m:ss", () => {
    expect(formatAtMs(0)).toBe("0:00");
    expect(formatAtMs(12_400)).toBe("0:12");
    expect(formatAtMs(75_000)).toBe("1:15");
  });
});

import type { SVGProps } from "react";

/**
 * House icons (ban list, owner 2026-11-07: NO Lucide icons on any site).
 *
 * Hand-drawn 24x24 stroke icons in the style the codebase already uses
 * (components/studio/StudioShell.tsx `iconProps`, components/ui/Spinner.tsx):
 * fill none, stroke currentColor, strokeWidth 2, round caps/joins.
 *
 * Same props contract as the Lucide components they replace, so call sites
 * keep their JSX: `className`, `fill`, `strokeWidth`, `aria-hidden` and any
 * other SVG prop pass straight through to the <svg>. Props spread AFTER the
 * defaults, so an explicit fill="currentColor" (StudioPlayer play/pause) or
 * strokeWidth={3} (UploadPanel language check) wins.
 *
 * No sparkle icon lives here on purpose: the ban list forbids sparkle icons.
 * "Free MP4 exports carry a small watermark" (UploadPanel) uses BadgeCheck (circle + check) instead.
 */

type IconProps = SVGProps<SVGSVGElement>;

